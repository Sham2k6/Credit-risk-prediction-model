def engineer_features(df: pd.DataFrame) -> pd.DataFrame:
    """Add derived financial-ratio features that are predictive of risk."""
    df = df.copy()
    df["debt_to_income"] = (df["existing_debt"] + df["loan_amount"]) / df["annual_income"]
    df["credit_utilization"] = df["credit_balance"] / df["credit_limit"]
    df["loan_to_income"] = df["loan_amount"] / df["annual_income"]
    df["savings_to_debt"] = df["savings_balance"] / (df["existing_debt"] + 1)
    df["avg_credit_per_line"] = df["credit_limit"] / df["num_credit_lines"]
    df["delinquency_score"] = df["num_late_payments_24m"] + 2 * df["num_derogatory_marks"]
    return df
df = engineer_features(df)
target_col = "creditworthy"
X = df.drop(columns=[target_col])
y = df[target_col]
print(f"Dataset shape: {df.shape}")
