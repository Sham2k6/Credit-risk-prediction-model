RANDOM_STATE = 42
def generate_synthetic_credit_data(n_samples: int = 2000) -> pd.DataFrame:
    """
    Generate a synthetic but realistic personal-finance dataset.
    Each row = one applicant, with income, debt, payment history,
    credit utilization, loan details, etc. The target 'creditworthy'
    (1 = good risk, 0 = bad risk) is derived from a weighted mix of
    these features plus noise.
    """
    rng = np.random.default_rng(RANDOM_STATE)
    age = rng.integers(21, 70, n_samples)
    annual_income = rng.normal(55000, 22000, n_samples).clip(12000, 200000)
    employment_length_yrs = rng.integers(0, 35, n_samples)
    existing_debt = rng.normal(15000, 12000, n_samples).clip(0, 120000)
    credit_limit = rng.normal(20000, 10000, n_samples).clip(1000, 100000)
    credit_balance = (credit_limit * rng.uniform(0, 1, n_samples)).clip(0)
    num_credit_lines = rng.integers(1, 12, n_samples)
    num_late_payments_24m = rng.poisson(0.8, n_samples)
    num_derogatory_marks = rng.poisson(0.3, n_samples)
    credit_history_yrs = rng.integers(0, 30, n_samples)
    loan_amount = rng.normal(12000, 8000, n_samples).clip(500, 60000)
    loan_term_months = rng.choice([12, 24, 36, 48, 60], n_samples)
    savings_balance = rng.normal(8000, 9000, n_samples).clip(0, 100000)
    home_ownership = rng.choice(["RENT", "MORTGAGE", "OWN"], n_samples, p=[0.4, 0.4, 0.2])
    loan_purpose = rng.choice(
        ["debt_consolidation", "credit_card", "home_improvement",
         "major_purchase", "medical", "other"],
        n_samples, p=[0.30, 0.25, 0.15, 0.10, 0.10, 0.10]
    )
    df = pd.DataFrame({
        "age": age,
        "annual_income": annual_income.round(2),
        "employment_length_yrs": employment_length_yrs,
        "existing_debt": existing_debt.round(2),
        "credit_limit": credit_limit.round(2),
        "credit_balance": credit_balance.round(2),
        "num_credit_lines": num_credit_lines,
        "num_late_payments_24m": num_late_payments_24m,
        "num_derogatory_marks": num_derogatory_marks,
        "credit_history_yrs": credit_history_yrs,
        "loan_amount": loan_amount.round(2),
        "loan_term_months": loan_term_months,
        "savings_balance": savings_balance.round(2),
        "home_ownership": home_ownership,
        "loan_purpose": loan_purpose,
    })

    dti = (df["existing_debt"] + df["loan_amount"]) / df["annual_income"]
    utilization = df["credit_balance"] / df["credit_limit"]

    risk_score = (
        -2.5 * dti
        - 1.8 * utilization
        - 0.6 * df["num_late_payments_24m"]
        - 1.2 * df["num_derogatory_marks"]
        + 0.04 * df["credit_history_yrs"]
        + 0.00002 * df["annual_income"]
        + 0.00003 * df["savings_balance"]
        + 0.02 * df["employment_length_yrs"]
    )

    noise = rng.normal(0, 1.0, n_samples)
    prob_good = 1 / (1 + np.exp(-(risk_score + noise)))
    df["creditworthy"] = (prob_good > 0.5).astype(int)
    return df
df = generate_synthetic_credit_data(n_samples=2000)
